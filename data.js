export function ordered(points){
 const remaining=points.slice(),done=[remaining.shift()];
 while(remaining.length){const i=remaining.findIndex(p=>done.some(q=>Math.abs(p.x-q.x)+Math.abs(p.y-q.y)+Math.abs(p.z-q.z)===1));if(i<0)throw Error('模型不相連');done.push(remaining.splice(i,1)[0]);}
 return done;
}
